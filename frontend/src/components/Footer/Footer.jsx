/* =====================================================
   POLICY MODAL
===================================================== */

function PolicyModal({ policyKey, onClose }) {
  const policy = policies[policyKey];

  useEffect(() => {
    if (!policy) return undefined;

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    const handleKeyDown = (event) => {
      if (event.key === "Escape") onClose();
    };

    document.addEventListener("keydown", handleKeyDown);

    return () => {
      document.body.style.overflow = previousOverflow;
      document.removeEventListener("keydown", handleKeyDown);
    };
  }, [policy, onClose]);

  if (!policy) return null;

  return (
    <div
      className="footer-policy-overlay"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget) onClose();
      }}
    >
      <section
        className="footer-policy-modal"
        role="dialog"
        aria-modal="true"
        aria-labelledby="footer-policy-title"
      >
        <header className="footer-policy-header">
          <div className="footer-policy-heading">
            <span className="footer-policy-eyebrow">
              EDITOLOGIA · POLICIES
            </span>

            <h2 id="footer-policy-title">{policy.title}</h2>
          </div>

          <button
            type="button"
            className="footer-policy-close"
            onClick={onClose}
            aria-label="დახურვა"
          >
            <FaTimes />
          </button>
        </header>

        <div className="footer-policy-body">
          {policy.sections.map((section, index) => (
            <article
              className="footer-policy-section"
              key={`${policyKey}-${index}`}
            >
              <h3>{section.title}</h3>
              <p>{section.content.trim()}</p>
            </article>
          ))}
        </div>

        <footer className="footer-policy-footer">
          <span>EDITOLOGIA</span>

          <button
            type="button"
            className="footer-policy-done"
            onClick={onClose}
          >
            დახურვა
          </button>
        </footer>
      </section>
    </div>
  );
}

